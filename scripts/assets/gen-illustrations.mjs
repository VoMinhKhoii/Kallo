#!/usr/bin/env node
/**
 * Regenerates the Koboyo surface-state illustration cast for both apps.
 *
 * Koboyo (koboyo.com) publishes hand-drawn single-pen SVGs, free for
 * commercial use with no attribution. Each file is a root
 * `<svg fill="currentColor" viewBox="0 0 W H">` holding nothing but
 * `<path d="…">` children, which is why the records below can be plain data:
 * one viewBox plus the list of `d` strings, never concatenated.
 *
 * Two outputs per slug:
 *   - web    `lib/brand/illustrations/<animal>.ts` — one exported record per
 *            pose, rendered by `components/shared/surface-state/`.
 *   - mobile `apps/mobile-flutter/assets/illustrations/<slug>.svg` — the same
 *            markup with `aria-label` dropped and the root fill baked to
 *            `#141413`, because flutter_svg ignores `currentColor`.
 *
 *   node scripts/assets/gen-illustrations.mjs                 # fetch koboyo.com
 *   node scripts/assets/gen-illustrations.mjs --from <dir>    # read <slug>.svg
 *
 * Without `--from` the sources are fetched over HTTPS. In the agent sandbox
 * that traffic has to go through the proxy, so run it as
 * `NODE_USE_ENV_PROXY=1 node scripts/assets/gen-illustrations.mjs` (Node 22+
 * only honours HTTPS_PROXY for `fetch` when that variable is set).
 *
 * Validation is deliberately loud: a source that grows a second attribute on a
 * path, loses `fill="currentColor"`, or ships a non-integer viewBox fails the
 * run with the slug named rather than silently changing the brand.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..'
);
const WEB_OUT = path.join(REPO_ROOT, 'lib/brand/illustrations');
const MOBILE_OUT = path.join(
  REPO_ROOT,
  'apps/mobile-flutter/assets/illustrations'
);
const SOURCE_URL = 'https://koboyo.com/icons/svg';

/** The ink the mobile copies are baked with (KalloColors.text). */
const MOBILE_FILL = '#141413';

/**
 * One animal per surface area, pose per state — the cast approved on the
 * design canvas. Adding a slug here is the only sanctioned way to add an
 * illustration to either app.
 */
const CAST = {
  circle: {
    animal: 'capybara',
    error: 'capybara-stuck-jar',
    empty: 'capybara-telescope',
    emptyAlt: 'capybara-peeking-out-box',
    night: 'capybara-sleeping-hammock',
  },
  logging: {
    animal: 'otter',
    error: 'otter-tangled-string',
    empty: 'otter-peeking-out-box',
    night: 'otter-wrapped-blanket',
  },
  nutrition: {
    animal: 'sloth',
    error: 'sloth-tangled-string',
    empty: 'sloth-peeking-out-box',
    night: 'sloth-sleeping-hammock',
  },
  dashboard: {
    animal: 'hedgehog',
    error: 'hedgehog-stuck-jar',
    empty: 'hedgehog-peeking-out-box',
    night: 'hedgehog-napping-shoe',
  },
  system: {
    animal: 'seal',
    error: 'seal-sweeping-broom',
    empty: 'seal-holding-map',
    notFound: 'seal-telescope',
    offline: 'seal-hammock',
    night: 'seal-curled-up-asleep',
  },
};

const HEADER =
  '// Generated by scripts/assets/gen-illustrations.mjs from koboyo.com' +
  ' — do not edit by hand.\n';

/** `capybara-stuck-jar` → `CAPYBARA_STUCK_JAR`. */
function constName(slug) {
  return slug.replaceAll('-', '_').toUpperCase();
}

/** The slugs of one area, in cast order, skipping the animal name. */
function slugsOf(area) {
  return Object.entries(area)
    .filter(([key]) => key !== 'animal')
    .map(([, slug]) => slug);
}

function fail(slug, why) {
  throw new Error(`${slug}: ${why}`);
}

/**
 * Pulls the root `<svg …>` tag, its viewBox and every `<path>` out of a Koboyo
 * source, refusing anything that does not match the shape we render.
 */
function parseSvg(slug, svg) {
  const root = svg.match(/<svg\b[^>]*>/);
  if (!root) fail(slug, 'no <svg> root element');
  const rootTag = root[0];
  if (!rootTag.includes('fill="currentColor"')) {
    fail(slug, 'root <svg> is missing fill="currentColor"');
  }
  const viewBox = rootTag.match(/viewBox="(0 0 \d+ \d+)"/);
  if (!viewBox) {
    fail(slug, 'root <svg> has no integer viewBox="0 0 W H"');
  }

  const paths = [];
  for (const match of svg.matchAll(/<path\b([^>]*?)\/?>/g)) {
    const attrs = [...match[1].matchAll(/([\w:-]+)="([^"]*)"/g)];
    const extra = attrs.filter(([, name]) => name !== 'd');
    if (extra.length > 0) {
      const names = extra.map(([, name]) => name).join(', ');
      fail(slug, `<path> carries attributes other than d (${names})`);
    }
    if (attrs.length !== 1) fail(slug, '<path> has no d attribute');
    paths.push(attrs[0][2]);
  }
  if (paths.length === 0) fail(slug, 'no <path> children');

  return { rootTag, viewBox: viewBox[1], paths };
}

/** Reads one source SVG from `--from <dir>`, or from koboyo.com. */
async function loadSvg(slug, fromDir) {
  if (fromDir) {
    return readFileSync(path.join(fromDir, `${slug}.svg`), 'utf8');
  }
  const response = await fetch(`${SOURCE_URL}/${slug}.svg`);
  if (!response.ok) {
    fail(slug, `fetch failed with HTTP ${response.status}`);
  }
  return await response.text();
}

/** The mobile copy: no aria-label, ink baked in place of currentColor. */
function mobileSvg(svg, rootTag) {
  const baked = rootTag
    .replace(/\s+aria-label="[^"]*"/, '')
    .replace('fill="currentColor"', `fill="${MOBILE_FILL}"`);
  return svg.replace(rootTag, baked);
}

/** One animal module: every pose of that animal as an exported record. */
function webModule(records) {
  const consts = records.map((record) => {
    const paths = record.paths
      .map((d) => `    ${JSON.stringify(d)},`)
      .join('\n');
    return (
      `export const ${constName(record.slug)}: Illustration = {\n` +
      `  slug: ${JSON.stringify(record.slug)},\n` +
      `  viewBox: ${JSON.stringify(record.viewBox)},\n` +
      `  paths: [\n${paths}\n  ],\n};\n`
    );
  });
  return (
    `${HEADER}\n` +
    "import type { Illustration } from '@/lib/brand/illustrations/illustration';\n\n" +
    consts.join('\n')
  );
}

async function main() {
  const fromFlag = process.argv.indexOf('--from');
  const fromDir =
    fromFlag === -1 ? null : path.resolve(process.argv[fromFlag + 1] ?? '');
  if (fromFlag !== -1 && !fromDir) {
    throw new Error('--from needs a directory');
  }

  mkdirSync(WEB_OUT, { recursive: true });
  mkdirSync(MOBILE_OUT, { recursive: true });

  const rows = [];
  for (const area of Object.values(CAST)) {
    const records = [];
    for (const slug of slugsOf(area)) {
      const svg = await loadSvg(slug, fromDir);
      const { rootTag, viewBox, paths } = parseSvg(slug, svg);
      records.push({ slug, viewBox, paths });

      const mobile = mobileSvg(svg, rootTag);
      writeFileSync(path.join(MOBILE_OUT, `${slug}.svg`), mobile);
      rows.push({
        slug,
        viewBox,
        bytes: Buffer.byteLength(mobile),
        paths: paths.length,
      });
    }
    writeFileSync(path.join(WEB_OUT, `${area.animal}.ts`), webModule(records));
  }

  execFileSync(
    'bunx',
    ['@biomejs/biome', 'check', '--write', 'lib/brand/illustrations'],
    { cwd: REPO_ROOT, stdio: 'inherit' }
  );

  const width = Math.max(...rows.map((row) => row.slug.length));
  console.log(
    `${'slug'.padEnd(width)}  ${'viewBox'.padEnd(12)}  ${'bytes'.padStart(6)}  paths`
  );
  for (const row of rows) {
    console.log(
      `${row.slug.padEnd(width)}  ${row.viewBox.padEnd(12)}  ` +
        `${String(row.bytes).padStart(6)}  ${row.paths}`
    );
  }
  const total = rows.reduce((sum, row) => sum + row.bytes, 0);
  console.log(`${rows.length} illustrations, ${total} bytes of SVG`);
}

await main();
